import { promises as fs } from 'node:fs';
import path from 'node:path';
import { env } from '../config/env';

/**
 * Where uploaded file BYTES live (metadata lives in the `documents` table, `storageKey`).
 * Swap the implementation (S3, persistent disk…) without touching callers.
 * SHARED CONTRACT: the documents module writes, the AI ingestion module reads.
 */
export interface FileStorage {
  save(key: string, data: Buffer): Promise<void>;
  read(key: string): Promise<Buffer>;
  remove(key: string): Promise<void>;
}

class LocalDiskStorage implements FileStorage {
  private readonly root: string;

  constructor(dir: string) {
    this.root = path.resolve(dir);
  }

  // Keys are generated by the server (never user-provided), but guard against traversal anyway.
  private resolve(key: string): string {
    const full = path.resolve(this.root, key);
    if (full !== this.root && !full.startsWith(this.root + path.sep)) {
      throw new Error('Invalid storage key');
    }
    return full;
  }

  async save(key: string, data: Buffer): Promise<void> {
    const full = this.resolve(key);
    await fs.mkdir(path.dirname(full), { recursive: true });
    await fs.writeFile(full, data);
  }

  read(key: string): Promise<Buffer> {
    return fs.readFile(this.resolve(key));
  }

  async remove(key: string): Promise<void> {
    await fs.rm(this.resolve(key), { force: true });
  }
}

let storage: FileStorage | undefined;

export function getStorage(): FileStorage {
  storage ??= new LocalDiskStorage(env.UPLOAD_DIR);
  return storage;
}

/** Tests may inject an in-memory or temp-dir implementation. */
export function setStorageForTests(impl: FileStorage | undefined): void {
  storage = impl;
}
